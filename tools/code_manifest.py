"""Regenerate manifest/code_manifest.tsv: path, md5 (first 12 hex), bytes and kind of every git-tracked file except uv.lock and the
manifest itself. Kinds of files already listed are kept; new files get a kind from their directory (see KIND).
usage: python tools/code_manifest.py [repo root]"""

import sys

if sys.argv[1:2] in (["-h"], ["--help"]):
    sys.exit(print(__doc__))

import hashlib, os, subprocess, sys

R = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(R, "manifest/code_manifest.tsv")
HEAD = "# Every file of this repository except uv.lock: path, md5 (first 12 hex), bytes, kind. Generated by tools/code_manifest.py.\n"
KIND = [
    ("tests/", "test"),
    ("baseline/", "baseline"),
    ("research/", "research"),
    (".github/", "ci"),
    ("tools/", "tool"),
    ("kumo_gpu/", "Kumo engine"),
    ("phase2/", "pipeline"),
    ("scripts/", "code"),
    ("docs/", "docs"),
    ("env/", "environment"),
]
old = {}
if os.path.exists(OUT):
    for line in open(OUT):
        f = line.rstrip("\n").split("\t")
        if len(f) == 4 and not line.startswith("#") and f[0] != "path":
            old[f[0]] = f[3]
files = subprocess.run(["git", "ls-files"], cwd=R, capture_output=True, text=True, check=True).stdout.split("\n")
rows = []
for p in sorted(x for x in files if x and x not in ("uv.lock", "manifest/code_manifest.tsv")):
    b = open(os.path.join(R, p), "rb").read()
    kind = old.get(p) or next((k for pre, k in KIND if p.startswith(pre)), "project file")
    rows.append(f"{p}\t{hashlib.md5(b).hexdigest()[:12]}\t{len(b)}\t{kind}\n")
open(OUT, "w").write(HEAD + "path\tmd5\tbytes\tkind\n" + "".join(rows))
print(f"wrote {OUT}: {len(rows)} files")
